# ======================= state =======================
function Source-Keys {
    $keys = @()
    foreach ($k in $SOURCE_ORDER) {
        $d = $SOURCES[$k].Disc; if ($d -eq 'MP') { $d = 'NA' }
        if ($script:disc[$d].Ok) { $keys += $k }
    }
    return $keys
}
function Selected-Key($r) {
    $i = $r.Src.SelectedIndex
    if ($i -le 0) { return $null }
    return $r.Keys[$i - 1]
}
function Update-Row($r) {
    $k = Selected-Key $r
    $isMp = [bool]($k -and $SOURCES[$k].Disc -eq 'MP')
    $on = $script:disc['NA'].Ok
    $r.Col.Enabled = $on -and $isMp
    $r.Col.BackColor = if ($r.Col.Enabled) { $C_CTRL } else { $C_FADED }
    $r.HCb.Visible = $r.HChk.Checked
    $same = [bool]($k -and (($k -eq "NA$($r.Slot)") -or ($k -eq 'NA14' -and $r.Slot -ge $FIRST_SLOT)))
    $r.Note.Visible = $same
}
function Refresh-Sources {
    $script:setting = $true
    try {
        $keys = Source-Keys
        foreach ($r in $script:rows) {
            $cur = Selected-Key $r
            $r.Src.Items.Clear(); [void]$r.Src.Items.Add($KEEP)
            foreach ($k in $keys) { [void]$r.Src.Items.Add($SOURCE_DISPLAY[$k]) }
            $r.Keys = $keys
            $idx = if ($cur -and $keys -contains $cur) { 1 + [array]::IndexOf($keys, $cur) } else { 0 }
            $r.Src.SelectedIndex = $idx
            Update-Row $r
        }
    } finally { $script:setting = $false }
    Update-Space
    Relayout
}
function Update-Space {
    $keys = @()
    foreach ($r in $script:rows) {
        $k = Selected-Key $r
        if (-not $k) { $k = if ($r.Slot -ge $FIRST_SLOT) { 'NA14' } else { "NA$($r.Slot)" } }
        $keys += $k
    }
    $used = if ($script:disc['NA'].Ok) { Get-SpaceUsed $keys } else { 0 }
    $cap = $DATA_END - $DATA_START
    $script:spaceOk = $used -le $cap
    $w = [int]([Math]::Min(1.0, $used / $cap) * 638)
    $barFill.Size = New-Object System.Drawing.Size($w, 20)
    $barFill.BackColor = if ($script:spaceOk) { $C_BLUE } else { $C_RED }
    $lblSpaceVal.Text = ('{0:N0} / {1:N0} sectors{2}' -f $used, $cap, $(if ($script:spaceOk) { '' } else { '   - too much, choose smaller skins' }))
    $lblSpaceVal.ForeColor = if ($script:spaceOk) { $C_TEXT } else { $C_RED }
    $btnPatch.Enabled = $script:disc['NA'].Ok -and $script:spaceOk
}
function Update-State {
    $naOk = $script:disc['NA'].Ok
    $chkUnlock.Enabled = $naOk
    foreach ($c in @($lblUnlockDesc, $lblTitle, $lblNotes, $lblSpace) + $noteLines) { $c.ForeColor = if ($naOk) { $C_TEXT } else { $C_DIM } }
    foreach ($r in $script:rows) {
        $r.Src.Enabled = $naOk; $r.HChk.Enabled = $naOk; $r.HCb.Enabled = $naOk
        foreach ($c in @($r.Num, $r.Name, $r.Arrow)) { $c.ForeColor = if ($naOk) { $C_TEXT } else { $C_DIM } }
    }
    Refresh-Sources
}
function Check-Disc([string]$role) {
    $d = $script:disc[$role]
    $path = $d.Box.Text
    if ($path -eq $d.Checked) { return }
    $d.Checked = $path
    $t = Test-Disc $path $role
    $d.Ok = [bool]$t.Ok
    if ($t.Ok) { $script:discSizes[$role] = $t.Sizes } else { $script:discSizes.Remove($role) }
    if ($t.Empty) { $d.Mark.Text = '' }
    elseif ($t.Ok) { $d.Mark.Text = $CHECK; $d.Mark.ForeColor = $C_GREEN; Log $t.Reason 'Green' }
    else { $d.Mark.Text = $CROSS; $d.Mark.ForeColor = $C_RED; Log $t.Reason 'Red' }
    Update-State
}

