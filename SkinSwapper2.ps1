    $start = [long]::MaxValue; $end = 0
    foreach ($pk in $pks) {
        $start = [Math]::Min($start, [Math]::Min($pk.Vif, $pk.Vtx))
        $end = [Math]::Max($end, [Math]::Max($pk.Vif + 16 * $pk.VifSize, $pk.Vtx + 16 * $pk.VtxSize))
    }
    if ($end -gt $gifOfs) { throw 'Packet data overlaps the texture usage table (unexpected).' }
    $newStart = [int]([Math]::Ceiling((0x10 + 16 * $n) / 16.0) * 16)
    $shift = $newStart - $start
    $body = New-Object byte[] ($end - $start)
    [Array]::Copy($m, [int]$start, $body, 0, $body.Length)
    $count = 0
    foreach ($pk in $pks) {
        foreach ($ref in (Get-JointRefs $m $pk)) {
            $j = Get-JointValue $m $ref
            if ($j -ge 86) { throw ('Joint {0} out of range in packet {1}.' -f $j, $pk.Index) }
            $nj = [int]$JOINT_MAP[$j]
            $bo = [int]($ref[1] - $start)
            if ($ref[0] -eq 'byte') { $body[$bo] = [byte]$nj }
            else { $v = U16 $m $ref[1]; Put16 $body $bo (($v -band 0x1FF) -bor ($nj -shl 9)) }
            $count++
        }
    }
    $gif = New-Object System.Collections.Generic.List[byte]
    $g = $gifOfs
    for ($guard = 0; $guard -lt 256; $guard++) {
        $ent = New-Object byte[] 16
        [Array]::Copy($m, $g, $ent, 0, 16)
        $ot = U32 $ent 12
        $off = ($ot -band 0xFFFFFF) + $shift
        if ($off -le 0) { throw 'Bad texture usage offset.' }
        Put32 $ent 12 (($ot -band 0xFF000000L) -bor $off)
        $gif.AddRange($ent); $g += 16
        if (($ot -shr 24) -eq 0x80) { break }
    }
    $gifNew = [int]([Math]::Ceiling(($newStart + $body.Length) / 16.0) * 16)
    $total = [int]([Math]::Ceiling(($gifNew + $gif.Count) / [double]$SECTOR) * $SECTOR)
    $out = New-Object byte[] $total
    [Array]::Copy($m, 4, $out, 0, 4)
    Put32 $out 4 0x10
    Put32 $out 8 $gifNew
    for ($i = 0; $i -lt $n; $i++) {
        $so = $pt + 16 * $i; $do = 0x10 + 16 * $i
        [Array]::Copy($m, $so, $out, $do, 16)
        Put32 $out $do ($pks[$i].Vif + $shift)
        Put32 $out ($do + 8) ($pks[$i].Vtx + $shift)
    }
    [Array]::Copy($body, 0, $out, $newStart, $body.Length)
    $gif.CopyTo($out, $gifNew)
    return [pscustomobject]@{ Mesh = $out; Joints = $count }
}
function Test-SpSkin([byte[]]$m) {
    $hi = [int]$m[0]; $lo = [int]$m[1]; $metal = [int]$m[2]
    if ((I32 $m 4) -ne 0x10) { throw 'Self-check: bad packet table offset.' }
    $pks = Get-Packets $m 0x10 ($hi + $lo + $metal) ($hi + $lo)
    $valid = New-Object 'System.Collections.Generic.HashSet[int]'
    foreach ($x in $JOINT_MAP) { [void]$valid.Add([int]$x) }
    foreach ($pk in $pks) {
        if ($pk.Vif + 16 * $pk.VifSize -gt $m.Length -or $pk.Vtx + 16 * $pk.VtxSize -gt $m.Length) { throw 'Self-check: packet outside the model.' }
        foreach ($ref in (Get-JointRefs $m $pk)) {
            if (-not $valid.Contains((Get-JointValue $m $ref))) { throw 'Self-check: joint not in the SP skeleton.' }
        }
    }
}
function Set-TeamColour([byte[]]$mpMesh, [byte[]]$tex, [int]$colour) {
