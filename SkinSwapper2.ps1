function Get-Packets([byte[]]$m, [int]$tableOfs, [int]$count, [int]$firstMetal) {
    $res = @()
    for ($i = 0; $i -lt $count; $i++) {
        $o = $tableOfs + 16 * $i
        $res += ,([pscustomobject]@{
            Index = $i; Vif = (U32 $m $o); VifSize = (U16 $m ($o + 4)); Vtx = (U32 $m ($o + 8))
            VtxSize = [int]$m[$o + 12]; Tvc = [int]$m[$o + 15]; Metal = ($i -ge $firstMetal)
        })
    }
    return ,$res
}
function Get-JointRefs([byte[]]$m, $pk) {
    $refs = New-Object System.Collections.Generic.List[object]
    if ($pk.Metal) {
        $nv = I32 $m ([int]$pk.Vtx)
        for ($k = 0; $k -lt $nv; $k++) {
            $vo = [int]$pk.Vtx + 16 + 16 * $k
            $refs.Add(@('byte', ($vo + 8))); $refs.Add(@('byte', ($vo + 9)))
        }
        return ,$refs
    }
    $o = [int]$pk.Vtx
    $mt = U16 $m $o; $two = U16 $m ($o + 2); $three = U16 $m ($o + 4); $main = U16 $m ($o + 6)
    $tvc = U16 $m ($o + 10); $vto = U16 $m ($o + 12)
    if ($tvc -ne $pk.Tvc) { throw ('Packet {0}: vertex count mismatch ({1} vs {2}).' -f $pk.Index, $tvc, $pk.Tvc) }
    for ($k = 0; $k -lt $mt; $k++) { $refs.Add(@('byte', ($o + 16 + 2 * $k))) }
    $nv = $two + $three + $main
    for ($k = 0; $k -lt $nv; $k++) {
        if ($k -ge $two -and $k -lt ($two + $three)) { continue }
        $refs.Add(@('bits', ($o + $vto + 16 * $k)))
    }
    return ,$refs
}
function Get-JointValue([byte[]]$m, $ref) {
    if ($ref[0] -eq 'byte') { return [int]$m[$ref[1]] }
    return ((U16 $m $ref[1]) -shr 9) -band 0x7F
}
