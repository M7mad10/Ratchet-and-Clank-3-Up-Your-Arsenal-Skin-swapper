}
function Get-PatchWord($lv, $pt, [int]$count) {
    $o = $pt.Orig; $base = $lv.RegionVA + $R_HELPER
    switch ($pt.New) {
        'KEEP' { return $o }
        # unlock function: "sltiu v0,a0,14" = slots 14+ (and 10) unlocked, game rule for the rest;
        # "sltiu v0,a0,0" = every skin counts as unlocked (no titanium-bolt purchase needed)
        'UNL'  { if ($script:unlockAll) { return 0x2C820000L } else { return 0x2C82000EL } }
        # "addiu v0,zero,10" = Constructobot always unlocked (old tools); -1 = game rule (needs the trophies)
        'UNL10' { if ($script:unlockAll) { return 0x2402000AL } else { return 0x2402FFFFL } }
        'MAPJ' { return 0x0C000000L -bor ((($base + $H_MAP) -shr 2) -band 0x3FFFFFF) }
        'CNT'  { return ($o -band 0xFFFF0000L) -bor $count }
        'END'  { return ($o -band 0xFFFF0000L) -bor (16 * $count) }
        'BHI'  { return ($o -band 0xFFFF0000L) -bor (($NAMEBUF + 0x8000) -shr 16) }
        'BLO'  { return ($o -band 0xFFFF0000L) -bor ($NAMEBUF -band 0xFFFF) }
        'BSZ'  { return ($o -band 0xFFFF0000L) -bor (68 * $count + 0x40) }
        'JAL0' { return 0x0C000000L -bor ((($base + $H_SITES[0]) -shr 2) -band 0x3FFFFFF) }
        'JAL1' { return 0x0C000000L -bor ((($base + $H_SITES[1]) -shr 2) -band 0x3FFFFFF) }
        'JAL2' { return 0x0C000000L -bor ((($base + $H_SITES[2]) -shr 2) -band 0x3FFFFFF) }
        default { return (Hex $pt.New) }
    }
}
# Places every own-text string into the free text areas: returns @{ string = @(area, offset) }.
function Layout-Text($strings) {
    $where = @{}; $pos = @(); foreach ($a in $TEXT_AREAS) { $pos += $a[1] }
    foreach ($s in $strings) {
        $len = [System.Text.Encoding]::ASCII.GetByteCount($s) + 1
        $done = $false
        for ($i = 0; $i -lt $TEXT_AREAS.Count; $i++) {
            if ($pos[$i] + $len -le $TEXT_AREAS[$i][2]) { $where[$s] = @($TEXT_AREAS[$i][0], $pos[$i]); $pos[$i] += $len; $done = $true; break }
        }
        if (-not $done) { throw 'Too much own menu text for the free space.' }
    }
    $used = 0; $total = 0
    for ($i = 0; $i -lt $TEXT_AREAS.Count; $i++) { $used += $pos[$i] - $TEXT_AREAS[$i][1]; $total += $TEXT_AREAS[$i][2] - $TEXT_AREAS[$i][1] }
    return [pscustomobject]@{ Where = $where; Used = $used; Total = $total }
}
function Text-Value($t, $layout, $lv, $hv) {
    if ($t -is [string]) {
        $w = $layout.Where[$t]
        if ($w[0] -eq 'R') { return $lv.RegionVA + $w[1] } else { return $hv.DeadRam + $w[1] }
    }
    return [long]$t
}
# Menu block of one level: skins list, helper code, per-skin map, own text (area R).
function Build-Region($lv, $hv, $entries, $stockNames, $mapTab, $layout) {
    $r = New-Object byte[] $REGION_LEN
    $stockBytes = Hex-Bytes $STOCK_LIST
    [Array]::Copy($stockBytes, 0, $r, 0, $stockBytes.Length)
    $base = $lv.RegionVA + $R_HELPER
    $tab = $base + $H_TAB
    $words = $HELPER_WORDS.Split(' ')
    for ($k = 0; $k -lt $words.Length; $k++) {
        $w = switch ($words[$k]) {
            'JCOM'  { 0x08000000L -bor ((($base + $H_COMMON) -shr 2) -band 0x3FFFFFF) }
            'JALLK' { 0x0C000000L -bor ($lv.TextJ -band 0x3FFFFFF) }
            'JLK'   { $lv.TextJ }
            'THI'   { 0x3C090000L -bor ((($tab + 0x8000) -shr 16) -band 0xFFFF) }
            'TLO'   { 0x91230000L -bor ($tab -band 0xFFFF) }
            default { Hex $words[$k] }
        }
        Put32 $r ($R_HELPER + 4 * $k) $w
    }
    for ($s = 0; $s -lt $SLOTS; $s++) { $r[$R_HELPER + $H_TAB + $s] = [byte]$mapTab[$s] }
    foreach ($s in $stockNames.Keys) {                       # renamed stock entries (slots 5-13)
        $e = 16 * ($s - 4)
        Put32 $r $e (Text-Value $stockNames[$s][0] $layout $lv $hv); Put32 $r ($e + 4) (Text-Value $stockNames[$s][1] $layout $lv $hv)
    }
    $k = $STOCK
    foreach ($en in $entries) {                              # new entries (slots 14-28), slot order
        $e = 16 * $k; $k++
        Put32 $r $e (Text-Value $en[1] $layout $lv $hv); Put32 $r ($e + 4) (Text-Value $en[2] $layout $lv $hv)
        Put32 $r ($e + 8) 0; Put32 $r ($e + 12) $en[0]
    }
    foreach ($t in $layout.Where.Keys) {
        $w = $layout.Where[$t]
        if ($w[0] -eq 'R') { $b = [System.Text.Encoding]::ASCII.GetBytes($t); [Array]::Copy($b, 0, $r, $w[1], $b.Length) }
    }
    return ,$r
}
# Helmet routine block of one level: routine, override table, magic, own text (area H).
function Build-HelmetBlob($hv, [byte[]]$table, $layout) {
    $t = $hv.DeadRam + $HTABLE_REL
    $lo = $t -band 0xFFFF; $hi = ($t -shr 16) + $(if ($lo -band 0x8000) { 1 } else { 0 })
    $words = $HELMET_HELPER.Split(' ')
    $blob = New-Object byte[] $DEAD_SIZE
    for ($k = 0; $k -lt $words.Length; $k++) {
        $w = switch ($words[$k]) { 'HI' { 0x3C030000L -bor ($hi -band 0xFFFF) } 'LO' { 0x90630000L -bor $lo } default { Hex $words[$k] } }
        [Array]::Copy((Word-Bytes $w), 0, $blob, 4 * $k, 4)
    }
    [Array]::Copy($MAGIC, 0, $blob, $MAGIC_REL, $MAGIC.Length)
    [Array]::Copy($table, 0, $blob, $HTABLE_REL, $SLOTS)
    foreach ($s in $layout.Where.Keys) {
        $w = $layout.Where[$s]
        if ($w[0] -eq 'H') { $b = [System.Text.Encoding]::ASCII.GetBytes($s); [Array]::Copy($b, 0, $blob, $w[1], $b.Length) }
    }
    return ,$blob
}


