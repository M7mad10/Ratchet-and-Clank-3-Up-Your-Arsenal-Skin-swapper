# Insomniac "WAD" decompression (same algorithm as Wrench's compression.cpp), compiled once with
# the C# compiler that comes with Windows (much faster than a PowerShell loop).
function Init-WadDecoder {
    if ('UyaWad' -as [type]) { return }
    Add-Type -TypeDefinition @"
public static class UyaWad {
    public static byte[] Decompress(byte[] src, int outSize) {
        if (src.Length < 16 || src[0] != 0x57 || src[1] != 0x41 || src[2] != 0x44) throw new System.Exception("No WAD header.");
        int end = System.BitConverter.ToInt32(src, 3);
        if (end > src.Length) throw new System.Exception("WAD data is cut off.");
        byte[] d = new byte[outSize]; int n = 0; int p = 16; int begin = 16;
        while (p < end) {
            int flag = src[p++]; int lb = -1; int ms = 0;
            if (flag < 0x10) {
                int lit = flag != 0 ? flag + 3 : src[p++] + 18;
                System.Buffer.BlockCopy(src, p, d, n, lit); p += lit; n += lit;
                continue;
            }
            if (flag < 0x20) {
                ms = flag & 7;
                if (ms == 0) ms = src[p++] + 7;
                int b0 = src[p++]; int b1 = src[p++];
                lb = n - ((flag & 8) * 0x800) - (b1 * 0x40) - (b0 >> 2);
                if (lb != n) { ms += 2; lb -= 0x4000; }
                else if (ms != 1) { while (((p - begin) % 0x1000) != 0) p++; continue; }
            } else if (flag < 0x40) {
                ms = flag & 0x1f;
                if (ms == 0) ms = src[p++] + 0x1f;
                ms += 2;
                int b1 = src[p++]; int b2 = src[p++];
                lb = n - (b2 * 0x40) - (b1 >> 2) - 1;
            } else {
                int b1 = src[p++];
                lb = n - b1 * 8 - ((flag >> 2) & 7) - 1;
                ms = (flag >> 5) + 1;
            }
            if (ms != 1) {
                if (lb < 0 || lb >= n) throw new System.Exception("Bad WAD data.");
                for (int i = 0; i < ms; i++) d[n + i] = d[lb + i];
                n += ms;
            }
            int little = src[p - 2] & 3;
            System.Buffer.BlockCopy(src, p, d, n, little); p += little; n += little;
        }
        if (n != outSize) throw new System.Exception("WAD size mismatch.");
        return d;
    }
}
"@
}
# Reads MP Ratchet from a multiplayer level: the class (header, animations, mesh, team palettes)
# and the pixels of its 2 textures (128x128, 8-bit).
function Get-MpRatchet([System.IO.FileStream]$fs) {
    $toc = Read-At $fs ([long]$TOC_LBA * $SECTOR) $TOC_SIZE
    $ofs = 0
    while ($ofs + 8 -le $toc.Length) { $hs = I32 $toc $ofs; if ($hs -lt 8 -or $hs -gt 0xFFFF) { break }; $ofs += $hs }
    $levelData = @{}
    for ($i = 0; $i -lt 100; $i++) {
        $e = $ofs + $i * 24
        if ($e + 24 -gt $toc.Length) { break }
        for ($j = 0; $j -lt 3; $j++) {
            $lba = I32 $toc ($e + 8 * $j); $ho = ([long]$lba - $TOC_LBA) * $SECTOR
            if ($lba -le $TOC_LBA -or $ho + 0x60 -gt $toc.Length) { continue }
            if ((I32 $toc ([int]$ho)) -ne 0x60) { continue }
            $id = I32 $toc ([int]$ho + 8)
            $levelData[$id] = ([long](I32 $toc ([int]$ho + 4)) + (I32 $toc ([int]$ho + 0x10))) * $SECTOR
        }
    }
    Init-WadDecoder
    foreach ($lvId in $MPR_LEVELS) {
        if (-not $levelData.ContainsKey($lvId)) { continue }
        $base = $levelData[$lvId]
        $dh = Read-At $fs $base 0x60
        $idx = Read-At $fs ($base + (I32 $dh 8)) (I32 $dh 12)              # core index
        $gsOfs = I32 $dh 16; $gsSize = I32 $dh 20                           # GS RAM image (palettes, stash)
        $cOfs = I32 $dh 0x48; $cSize = I32 $dh 0x4C                         # compressed core data
        $classCount = I32 $idx 0x18; $classTab = I32 $idx 0x1C
        $entry = -1; $offsets = @()
        for ($k = 0; $k -lt $classCount; $k++) {
            $o = $classTab + 32 * $k
            $offsets += (I32 $idx $o)
            if ((I32 $idx ($o + 4)) -eq $MPR_CLASS) { $entry = $o }
        }
        if ($entry -lt 0) { continue }
        $start = I32 $idx $entry
        $next = [int]::MaxValue
        foreach ($x in $offsets) { if ($x -gt $start -and $x -lt $next) { $next = $x } }
        $core = [UyaWad]::Decompress((Read-At $fs ($base + $cOfs) $cSize), (I32 $idx 0x8C))
        if ($next -eq [int]::MaxValue) { $next = $core.Length }
        $cls = New-Object byte[] ($next - $start)
        [Array]::Copy($core, $start, $cls, 0, $cls.Length)
        # textures: class texture indices -> moby texture table (data offset, w, h, type, palette)
        $texTab = I32 $idx 0x3C; $texBase = I32 $idx 0x60
        $pix = @()
        for ($t = 0; $t -lt 16; $t++) {
            $ti = [int]$idx[$entry + 16 + $t]
            if ($ti -eq 0xFF) { break }
            $te = $texTab + 16 * $ti
            $w = [BitConverter]::ToInt16($idx, $te + 4); $h = [BitConverter]::ToInt16($idx, $te + 6)
            $px = New-Object byte[] ($w * $h)
            [Array]::Copy($core, $texBase + (I32 $idx $te), $px, 0, $px.Length)
            $pix += ,([pscustomobject]@{ W = $w; H = $h; Pixels = $px })
        }
        $allPix = @(); foreach ($x in $pix) { $allPix += $x.Pixels }
        $ok = ((Sha $cls) -eq $MPR_CLASS_SHA) -and ((Sha ([byte[]]$allPix)) -eq $MPR_PIX_SHA)
        return [pscustomobject]@{ Level = $lvId; Class = $cls; Textures = $pix; Original = $ok }
    }
    throw 'MP Ratchet was not found in the multiplayer levels of this disc.'
}
# Single-player texture block for MP Ratchet in one team colour: count, offsets, then one
# 8-bit PIF per texture with 4 mip levels (made by taking every 2nd pixel).
function Build-RatchetTex($mpr, [int]$colour) {
    $m = $mpr.Class
    $count = $mpr.Textures.Count
    $palBase = (I32 $m 0x20) - $count * 0x2000
    $parts = @()
    for ($k = 0; $k -lt $count; $k++) {
        $tx = $mpr.Textures[$k]
        $set = $palBase + $k * 0x2000
        $ms = New-Object System.IO.MemoryStream
        $ms.Write($m, $set + $colour * 0x400, 1024)
        $cur = $tx.Pixels; $w = $tx.W; $h = $tx.H
        for ($lvl = 0; $lvl -lt 4; $lvl++) {
            $ms.Write($cur, 0, $cur.Length)
            $nw = [int]($w / 2); $nh = [int]($h / 2)
            $nx = New-Object byte[] ($nw * $nh)
            for ($y = 0; $y -lt $nh; $y++) { for ($x = 0; $x -lt $nw; $x++) { $nx[$y * $nw + $x] = $cur[(2 * $y) * $w + 2 * $x] } }
            $cur = $nx; $w = $nw; $h = $nh
        }
        $body = $ms.ToArray()
        $hdr = New-Object byte[] 32
        [Array]::Copy([System.Text.Encoding]::ASCII.GetBytes('2FIP'), 0, $hdr, 0, 4)
        Put32 $hdr 4 (32 + $body.Length); Put32 $hdr 8 $tx.W; Put32 $hdr 12 $tx.H; Put32 $hdr 16 0x13; Put32 $hdr 28 4
        $parts += ,(Join-Bytes $hdr $body)
    }
    $head = 4 + 4 * $count; $head = [int]([Math]::Ceiling($head / 16.0) * 16)
    $total = $head; $offs = @()
    foreach ($pp in $parts) { $offs += $total; $total += [int]([Math]::Ceiling($pp.Length / 16.0) * 16) }
    $out = New-Object byte[] ([int]([Math]::Ceiling($total / [double]$SECTOR) * $SECTOR))
    Put32 $out 0 $count
    for ($k = 0; $k -lt $count; $k++) { Put32 $out (4 + 4 * $k) $offs[$k]; [Array]::Copy($parts[$k], 0, $out, $offs[$k], $parts[$k].Length) }
    return ,$out
}

# ======================= discs =======================
function Open-Disc([string]$path) {
    if (-not (Test-Path -LiteralPath $path)) { throw "File not found: $path" }
    $fs = [System.IO.File]::Open($path, [System.IO.FileMode]::Open, [System.IO.FileAccess]::Read, [System.IO.FileShare]::Read)
    $pvd = Read-At $fs (16 * $SECTOR) $SECTOR
    if ([System.Text.Encoding]::ASCII.GetString($pvd, 1, 5) -ne 'CD001') { $fs.Close(); throw "Not a plain .iso (convert .chd/.cso first): $path" }
    return $fs
}
# The ARMOR table of a UYA (29 skin slots) or Going Commando (9) disc.
function Read-SkinDisc([System.IO.FileStream]$fs, [string]$label) {
    $toc = Read-At $fs ([long]$TOC_LBA * $SECTOR) $TOC_SIZE
    $ofs = 0; $at = -1; $hs = 0
    while ($ofs + 8 -le $toc.Length) {
        $h = I32 $toc $ofs
        if ($h -lt 8 -or $h -gt 0xFFFF) { break }
        if ($h -eq $HDR_UYA -or $h -eq $HDR_GC) { $at = $ofs; $hs = $h; break }
        $ofs += $h
    }
    if ($at -lt 0) { throw "$label : could not find the ARMOR file. Is this Up Your Arsenal or Going Commando?" }
    $tbl = New-Object byte[] $hs
    [Array]::Copy($toc, $at, $tbl, 0, $hs)
    $wadPos = [long](I32 $tbl 4) * $SECTOR
    $copy = Read-At $fs $wadPos $hs
    for ($j = 8; $j -lt $hs; $j++) { if ($copy[$j] -ne $tbl[$j]) { throw "$label : the two copies of the ARMOR table disagree." } }
    $game = if ($hs -eq $HDR_UYA) { 'UYA' } else { 'GC' }
    return [pscustomobject]@{ Game = $game; Count = $(if ($game -eq 'UYA') { 29 } else { 9 }); WadPos = $wadPos
                              TocPos = [long]$TOC_LBA * $SECTOR + $at; Table = $tbl }
}

