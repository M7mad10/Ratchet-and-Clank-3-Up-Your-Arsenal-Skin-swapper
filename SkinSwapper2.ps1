function Parse-MenuRows {
    $res = @{}
    foreach ($row in $MENU_ROWS) {
        $parts = $row.Split('|'); $h = $parts[0].Split(',')
        $pats = @(); $site = 0
        foreach ($t in $parts[2].Split(' ')) {
            $x = $t.Split(':')
            $ofs = Hex $x[0]; $orig = Hex $x[1]; $new = $x[2]
            if ($new -eq 'PSK') {
                $pats += ,([pscustomobject]@{ Ofs = $ofs; Orig = $orig; New = 'KEEP' })
                $pats += ,([pscustomobject]@{ Ofs = $ofs + 4; Orig = 0x001018C0L; New = 'MAPJ' })
                $pats += ,([pscustomobject]@{ Ofs = $ofs + 8; Orig = 0x00433821L; New = '0' })
                continue
            }
            if ($new -eq 'JAL') { $new = "JAL$site"; $site++ }
            if ($orig -eq 0x2C820008L -and $new -eq '2c82000e') { $new = 'UNL' }     # first word of the unlock function
            if ($new -eq '2402000a') { $new = 'UNL10' }                                # slot 10 (Constructobot) rule of the unlock function
            $pats += ,([pscustomobject]@{ Ofs = $ofs; Orig = $orig; New = $new })
        }
        if (@($pats | Where-Object { $_.New -eq 'UNL' }).Count -ne 1 -or @($pats | Where-Object { $_.New -eq 'UNL10' }).Count -ne 1) { throw 'Internal error: unlock function.' }
        $res[[int]$h[0]] = [pscustomobject]@{ Id = [int]$h[0]; Size = (Hex $h[1]); RegionOfs = (Hex $h[2]); RegionVA = (Hex $h[3]); TextJ = (Hex $h[4]); Pats = $pats }
    }
    return $res
}
