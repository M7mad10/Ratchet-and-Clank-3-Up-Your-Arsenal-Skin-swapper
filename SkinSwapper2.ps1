# ======================= disc checks (as in Skin Swapper v1) =======================
function Test-Disc([string]$path, [string]$role) {
    $label = $ROLE_NAME[$role]
    $path = $path.Trim().Trim('"').Trim()
    if (-not $path) { return @{ Ok = $false; Empty = $true; Reason = '' } }
    if (-not (Test-Path -LiteralPath $path -PathType Leaf)) { return @{ Ok = $false; Reason = "${label}: file not found: $path" } }
    $fs = $null
    try {
        try { $fs = [System.IO.File]::Open($path, [System.IO.FileMode]::Open, [System.IO.FileAccess]::Read, [System.IO.FileShare]::Read) }
        catch { return @{ Ok = $false; Reason = "${label}: the file can't be opened (is it in use?): $path" } }
        if ($fs.Length -lt 17 * $SECTOR) { return @{ Ok = $false; Reason = "${label}: not a plain .iso disc image (the file is too small)." } }
        $pvd = Read-At $fs (16 * $SECTOR) $SECTOR
        if ([System.Text.Encoding]::ASCII.GetString($pvd, 1, 5) -ne 'CD001') { return @{ Ok = $false; Reason = "${label}: not a plain .iso disc image (convert .chd/.cso/.bin to .iso first)." } }
        $serial = Get-Serial $fs
        if (-not $serial) { return @{ Ok = $false; Reason = "${label}: no PS2 game serial found on this disc." } }
        if ($ACCEPTED[$role] -notcontains $serial) {
            if ($KNOWN_SERIAL.ContainsKey($serial)) { return @{ Ok = $false; Reason = "${label}: this is $($KNOWN_SERIAL[$serial]) ($serial), not $label." } }
            return @{ Ok = $false; Reason = "${label}: version $serial isn't supported yet (supported: $($ACCEPTED[$role] -join ', '))." }
        }
        try { $d = Read-SkinDisc $fs $label } catch { return @{ Ok = $false; Reason = "${label}: can't read the game's file table ($($_.Exception.Message))." } }
        if (-not $script:NoShaCheck -and (Sha $d.Table) -ne $HEADER_SHA[$role]) {
            return @{ Ok = $false; Reason = "${label}: this copy's skin table is different from the original disc (already modified?). Use an unmodified $serial iso." }
        }
        $sizes = @()
        for ($s = 0; $s -lt $d.Count; $s++) { $f = 8 + 16 * $s; $sizes += ((I32 $d.Table ($f + 4)) + (I32 $d.Table ($f + 12))) }
        return @{ Ok = $true; Reason = "${label}: OK ($serial)"; Serial = $serial; Sizes = $sizes }
    } catch {
        return @{ Ok = $false; Reason = "${label}: can't read this file ($($_.Exception.Message))." }
    } finally { if ($fs) { $fs.Close() } }
}
function Unique-Path([string]$path) {
    if (-not (Test-Path -LiteralPath $path)) { return $path }
    $dir = Split-Path -Parent $path; $name = [System.IO.Path]::GetFileNameWithoutExtension($path)
    for ($n = 2; $n -lt 1000; $n++) {
        $p = Join-Path $dir ("{0} ({1}).iso" -f $name, $n)
        if (-not (Test-Path -LiteralPath $p)) { return $p }
    }
    throw 'Could not find a free output file name.'
}
# Copies the iso in chunks, keeping the window responsive and logging progress.
function Copy-WithProgress([string]$src, [string]$dst) {
    $in = [System.IO.File]::Open($src, [System.IO.FileMode]::Open, [System.IO.FileAccess]::Read, [System.IO.FileShare]::Read)
    $out = [System.IO.File]::Open($dst, [System.IO.FileMode]::CreateNew, [System.IO.FileAccess]::Write, [System.IO.FileShare]::None)
    try {
        $buf = New-Object byte[] (8MB); $total = $in.Length; $done = [long]0; $next = 10
        while ($true) {
            $n = $in.Read($buf, 0, $buf.Length)
            if ($n -le 0) { break }
            $out.Write($buf, 0, $n); $done += $n
            if ($script:UiPump) { & $script:UiPump }
            $pct = [int](100 * $done / $total)
            if ($pct -ge $next) { Log ("  copying... {0}%" -f $pct) 'DarkGray'; $next = $pct - ($pct % 10) + 10 }
        }
    } finally { $out.Close(); $in.Close() }
}

# ======================= the patch =======================
# $cfg: NA, JP, GC (paths or ''), UnlockAll (bool),
#       Slots: hashtable slot -> @{ Key = source key; Colour = 0-7; Helmet = 0 game / 1 off / 2-5 colour }
# Returns @{ Ok; Out; Error }
function Invoke-Patch($cfg) {
    $streams = @(); $outPath = $null; $made = $null
    try {
        $script:unlockAll = [bool]$cfg.UnlockAll
        # ---- discs
        $discs = @{}
        foreach ($role in 'NA', 'JP', 'GC') {
            $p = [string]$cfg.$role
            if (-not $p) { continue }
            $p = $p.Trim().Trim('"').Trim()
            $t = Test-Disc $p $role
            if (-not $t.Ok) { throw $t.Reason }
            $fs = Open-Disc $p; $streams += $fs
            $discs[$role] = [pscustomobject]@{ Path = $p; Stream = $fs; Skin = (Read-SkinDisc $fs $ROLE_NAME[$role]); Serial = $t.Serial }
        }
        if (-not $discs.ContainsKey('NA')) { throw 'NA UYA is needed.' }
        $na = $discs['NA']; $nfs = $na.Stream
        $armor = Get-Armor $nfs
        for ($s = 0; $s -lt $SLOTS; $s++) {
            $en = Get-Entry $armor.Table $s; $o = $NA_TABLE[$s]
            if ($en.MeshOfs -ne $o[0] -or $en.MeshSize -ne $o[1] -or $en.TexOfs -ne $o[2] -or $en.TexSize -ne $o[3]) { throw "NA UYA slot $s is not original. Use an unmodified NA UYA iso." }
        }
        $menuRows = Parse-MenuRows; $helmRows = Parse-HelmetRows
        $ov = Get-Overlays $nfs
        $stockBytes = Hex-Bytes $STOCK_LIST
        $levelIds = @($menuRows.Keys | Sort-Object)
        Log '  Checking the game code of the 34 single-player levels...'
        foreach ($id in $levelIds) {
            $lv = $menuRows[$id]; $hv = $helmRows[$id]
            if (-not $ov.ContainsKey($id) -or $ov[$id].Size -ne $lv.Size -or $hv.Size -ne $lv.Size) { throw "Level $id of NA UYA is different from the original disc." }
            $pos = $ov[$id].Pos
            $lv | Add-Member -NotePropertyName Pos -NotePropertyValue $pos -Force
            $reg = Read-At $nfs ($pos + $lv.RegionOfs) $REGION_LEN
            for ($q = 0; $q -lt 0x320; $q++) { if ($reg[$q] -ne 0) { throw "Level ${id}: the Skins menu was already changed. Use an unmodified NA UYA iso." } }
            for ($q = 0; $q -lt $stockBytes.Length; $q++) { if ($reg[0x320 + $q] -ne $stockBytes[$q]) { throw "Level ${id}: the skins list is not original. Use an unmodified NA UYA iso." } }
            foreach ($pt in $lv.Pats) { if ((U32 (Read-At $nfs ($pos + $pt.Ofs) 4) 0) -ne $pt.Orig) { throw ("Level {0}: unexpected game code at 0x{1:X}. Use an unmodified NA UYA iso." -f $id, $pt.Ofs) } }
            if ((Sha (Read-At $nfs ($pos + $hv.DeadOfs) $DEAD_SIZE)) -ne $hv.DeadSha) { throw "Level ${id}: the helmet code is not original. Use an unmodified NA UYA iso." }
            foreach ($hk in $hv.Hooks) { if ((U32 (Read-At $nfs ($pos + $hk.Ofs) 4) 0) -ne $hk.Orig) { throw "Level ${id}: the helmet code is not original. Use an unmodified NA UYA iso." } }
            if ($script:UiPump) { & $script:UiPump }
        }

        # ---- every slot: read or convert its source
        $jobs = @()
        for ($s = 0; $s -lt $SLOTS; $s++) {
            $c = $null; if ($cfg.Slots.ContainsKey($s)) { $c = $cfg.Slots[$s] }
            $key = if ($c -and $c.Key) { [string]$c.Key } elseif ($s -ge $FIRST_SLOT) { 'NA14' } else { "NA$s" }
            if ($key -match '^NA(1[4-9]|2[0-8])$') { $key = 'NA14' }
            if (-not $SOURCES.ContainsKey($key)) { throw "Slot ${s}: unknown source $key." }
            $colour = if ($c) { [int]$c.Colour } else { 0 }
            $helmet = if ($c) { [int]$c.Helmet } else { 0 }
            $src = $SOURCES[$key]
            $pl = [pscustomobject]@{ Slot = $s; Key = $key; Colour = $colour; ColName = $(if ($src.Disc -eq 'MP') { @($COLOURS.Keys)[$colour] } else { '' }); Helmet = $helmet; Feet = 0 }
            $mesh = $null; $tex = $null
            if ($src.Disc -eq 'MP') {
                if ($src.Slot -lt 0) {
                    if (-not $script:mpr) {
                        Log '  Reading MP Ratchet from the multiplayer level data...'
                        $script:mpr = Get-MpRatchet $nfs
                        if (-not $script:mpr.Original) { throw 'MP Ratchet on this disc is not the original data.' }
                    }
                    $conv = Convert-MpSkin $script:mpr.Class; Test-SpSkin $conv.Mesh
                    $mesh = $conv.Mesh; $tex = Build-RatchetTex $script:mpr $colour
                } else {
                    $d = Read-Entry $nfs $armor $src.Slot
                    if ((Sha (Join-Bytes $d.Mesh $d.Tex)) -ne $MP_SHA[$src.Slot]) { throw "MP skin $($src.Slot) on this disc is not the original data." }
                    $conv = Convert-MpSkin $d.Mesh; Test-SpSkin $conv.Mesh
                    $mesh = $conv.Mesh; $tex = Set-TeamColour $d.Mesh $d.Tex $colour
                }
            } else {
                if (-not $discs.ContainsKey($src.Disc)) { throw "Slot ${s}: $($SOURCE_DISPLAY[$key]) needs the $($ROLE_NAME[$src.Disc]) iso." }
                $dd = $discs[$src.Disc]
                $f = 8 + 16 * $src.Slot; $t = $dd.Skin.Table
                $ms = I32 $t ($f + 4); $ts = I32 $t ($f + 12)
                $mesh = Read-At $dd.Stream ($dd.Skin.WadPos + [long](I32 $t $f) * $SECTOR) ($ms * $SECTOR)
                $tex  = Read-At $dd.Stream ($dd.Skin.WadPos + [long](I32 $t ($f + 8)) * $SECTOR) ($ts * $SECTOR)
            }
            $msec = $mesh.Length / $SECTOR; $tsec = $tex.Length / $SECTOR
            if ($msec -gt $MAX_PART -or $tsec -gt $MAX_PART) { throw "Slot ${s}: $($SOURCE_DISPLAY[$key]) is too big for the game's skin memory." }
            $jobs += ,([pscustomobject]@{ Slot = $s; Plan = $pl; Src = $src; Mesh = $mesh; Tex = $tex; MeshSec = $msec; TexSec = $tsec; Placeholder = ($key -eq 'NA14') })
            if ($script:UiPump) { & $script:UiPump }
        }

        # ---- pack all slots into the space of slots 0-28 (placeholders share one copy)
        $pos = $DATA_START; $ph = $null
        foreach ($jb in $jobs) {
            if ($jb.Placeholder -and $ph) { $jb | Add-Member -NotePropertyName Entry -NotePropertyValue $ph; $jb | Add-Member -NotePropertyName Write -NotePropertyValue $false; continue }
            $e = @($pos, $jb.MeshSec, ($pos + $jb.MeshSec), $jb.TexSec)
            $jb | Add-Member -NotePropertyName Entry -NotePropertyValue $e; $jb | Add-Member -NotePropertyName Write -NotePropertyValue $true
            if ($jb.Placeholder) { $ph = $e }
            $pos += $jb.MeshSec + $jb.TexSec
        }
        $packedEnd = $pos
        if ($packedEnd -gt $DATA_END) { throw "The chosen skins need $($packedEnd - $DATA_START) sectors of disc space; only $($DATA_END - $DATA_START) are available." }

        # ---- menu, per-skin map, helmet table, text
        $entries = @(); $stockNames = @{}; $mapTab = New-Object int[] $SLOTS; $htable = New-Object byte[] $SLOTS; $own = @()
        foreach ($jb in $jobs) {
            $s = $jb.Slot; $src = $jb.Src
            $mapTab[$s] = $src.Pair; $htable[$s] = [byte]$jb.Plan.Helmet
            $isOriginal = ($jb.Plan.Key -eq "NA$s") -or ($s -ge $FIRST_SLOT -and $jb.Placeholder)
            if ($s -ge 5 -and $s -lt $FIRST_SLOT -and -not $isOriginal) { $stockNames[$s] = @($src.MenuName, $src.Desc) }
            if ($s -ge $FIRST_SLOT -and -not $jb.Placeholder) { $entries += ,@($s, $src.MenuName, $src.Desc) }
            if ($s -ge 5 -and -not $isOriginal) { foreach ($t in @($src.MenuName, $src.Desc)) { if ($t -is [string] -and $own -notcontains $t) { $own += $t } } }
        }
        $layout = Layout-Text $own
        $count = $STOCK + $entries.Count
        foreach ($jb in $jobs) {
            $isOriginal = ($jb.Plan.Key -eq "NA$($jb.Slot)") -or ($jb.Slot -ge $FIRST_SLOT -and $jb.Placeholder)
            $what = if ($isOriginal) { '(original)' } else { $SOURCE_DISPLAY[$jb.Plan.Key] }
            if ($jb.Plan.ColName -and -not $isOriginal) { $what += " $($jb.Plan.ColName)" }
            if ($jb.Plan.Helmet) { $what += '  helmet: ' + @('', 'none', 'orange', 'blue', 'red', 'green')[$jb.Plan.Helmet] }
            Log ('  Slot {0,2}: {1}' -f $jb.Slot, $what) $(if ($isOriginal) { 'DarkGray' } else { 'Gray' })
        }
        Log ("  Disc space: {0} of {1} sectors. Skins menu: {2} entries. Unlock all: {3}." -f ($packedEnd - $DATA_START), ($DATA_END - $DATA_START), $count, $(if ($script:unlockAll) { 'yes' } else { 'no' }))

        $plans = @()
        foreach ($id in $levelIds) {
            $lv = $menuRows[$id]; $hv = $helmRows[$id]
            $words = @()
            foreach ($pt in $lv.Pats) { $words += ,@($pt.Ofs, (Get-PatchWord $lv $pt $count)) }
            foreach ($hk in $hv.Hooks) { $words += ,@($hk.Ofs, (Hex $hk.New)) }
            $plans += [pscustomobject]@{ Lv = $lv; Hv = $hv; Region = (Build-Region $lv $hv $entries $stockNames $mapTab $layout); Helmet = (Build-HelmetBlob $hv $htable $layout); Words = $words }
        }

        # ---- write the new iso
        $base = [System.IO.Path]::GetFileNameWithoutExtension($na.Path)
        $outPath = if ($cfg.OutIso) { [string]$cfg.OutIso } else { Unique-Path (Join-Path (Split-Path -Parent $na.Path) ("{0} [modded].iso" -f $base)) }
        foreach ($d in $discs.Values) { if ($outPath -eq $d.Path) { throw 'The output must be a different file from the inputs.' } }
        if (Test-Path -LiteralPath $outPath) { throw "The output file already exists: $outPath" }
        foreach ($x in $streams) { $x.Close() }; $streams = @()
        Log "  Writing: $outPath"
        $made = $outPath
        Copy-WithProgress $na.Path $outPath
        $out = [System.IO.File]::Open($outPath, [System.IO.FileMode]::Open, [System.IO.FileAccess]::ReadWrite, [System.IO.FileShare]::None)
        try {
            $wadPos = $armor.WadPos
            Write-At $out ($wadPos + [long]$DATA_START * $SECTOR) (New-Object byte[] (($DATA_END - $DATA_START) * $SECTOR))
            foreach ($jb in $jobs) {
                if ($jb.Write) { Write-At $out ($wadPos + [long]$jb.Entry[0] * $SECTOR) $jb.Mesh; Write-At $out ($wadPos + [long]$jb.Entry[2] * $SECTOR) $jb.Tex }
                $eb = New-Object byte[] 16
                Put32 $eb 0 $jb.Entry[0]; Put32 $eb 4 $jb.Entry[1]; Put32 $eb 8 $jb.Entry[2]; Put32 $eb 12 $jb.Entry[3]
                Write-At $out ($armor.TocPos + 8 + 16 * $jb.Slot) $eb
                Write-At $out ($wadPos + 8 + 16 * $jb.Slot) $eb
            }
            foreach ($p in $plans) {
                Write-At $out ($p.Lv.Pos + $p.Lv.RegionOfs) $p.Region
                Write-At $out ($p.Lv.Pos + $p.Hv.DeadOfs) $p.Helmet
                foreach ($w in $p.Words) { Write-At $out ($p.Lv.Pos + $w[0]) (Word-Bytes $w[1]) }
            }
            $out.Flush()
            Log '  Checking what was written...'
            $a2 = Get-Armor $out
            for ($s = 0; $s -lt ($HDR_UYA - 8) / 16; $s++) {
                $en = Get-Entry $a2.Table $s
                if ($s -lt $SLOTS) { $e = $jobs[$s].Entry } else { $o = Get-Entry $armor.Table $s; $e = @($o.MeshOfs, $o.MeshSize, $o.TexOfs, $o.TexSize) }
                if ($en.MeshOfs -ne $e[0] -or $en.MeshSize -ne $e[1] -or $en.TexOfs -ne $e[2] -or $en.TexSize -ne $e[3]) { throw "Check failed: skin table entry $s." }
            }
            foreach ($jb in $jobs) {
                $back = Read-Entry $out $a2 $jb.Slot
                if ((Sha $back.Mesh) -ne (Sha $jb.Mesh) -or (Sha $back.Tex) -ne (Sha $jb.Tex)) { throw "Check failed: slot $($jb.Slot) data." }
            }
            foreach ($p in $plans) {
                if ((Sha (Read-At $out ($p.Lv.Pos + $p.Lv.RegionOfs) $REGION_LEN)) -ne (Sha $p.Region)) { throw "Check failed: level $($p.Lv.Id) skins menu." }
                if ((Sha (Read-At $out ($p.Lv.Pos + $p.Hv.DeadOfs) $DEAD_SIZE)) -ne (Sha $p.Helmet)) { throw "Check failed: level $($p.Lv.Id) helmet code." }
                foreach ($w in $p.Words) { if ((U32 (Read-At $out ($p.Lv.Pos + $w[0]) 4) 0) -ne $w[1]) { throw "Check failed: level $($p.Lv.Id) game code." } }
            }
        } finally { $out.Close() }
        return @{ Ok = $true; Out = $outPath }
    } catch {
        if ($made -and (Test-Path -LiteralPath $made)) { try { Remove-Item -LiteralPath $made -Force } catch { } }
        return @{ Ok = $false; Error = $_.Exception.Message }
    } finally {
        foreach ($x in $streams) { try { $x.Close() } catch { } }
    }
}

# Disc space a choice of sources needs (the same rules as the patch: placeholders share one copy).
function Get-SpaceUsed($keys) {
    $used = 0; $ph = $false
    foreach ($k in $keys) {
        if ($k -eq 'NA14') { if (-not $ph) { $used += $PH_SECTORS; $ph = $true }; continue }
        $src = $SOURCES[$k]
        if ($src.Disc -eq 'MP') { if ($src.Slot -lt 0) { $used += $MPR_SECTORS } else { $used += $MP_SIZES[$src.Slot] } }
        else { $sz = $script:discSizes[$src.Disc]; if ($sz) { $used += $sz[$src.Slot] } }
    }
    return $used
}

