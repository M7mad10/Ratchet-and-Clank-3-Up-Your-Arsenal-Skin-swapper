function Clean-Path([string]$p) { return $p.Trim().Trim('"').Trim("'").Trim() }
function Full-Path([string]$p) {
    $p = Clean-Path $p
    if (-not [System.IO.Path]::IsPathRooted($p)) { $p = Join-Path (Get-Location).Path $p }
    return [System.IO.Path]::GetFullPath($p)
}
function I32([byte[]]$b, [int]$o) { return [BitConverter]::ToInt32($b, $o) }
function U32([byte[]]$b, [int]$o) { return [long][BitConverter]::ToUInt32($b, $o) }
function U16([byte[]]$b, [int]$o) { return [int][BitConverter]::ToUInt16($b, $o) }
function Put32([byte[]]$b, [int]$o, [long]$v) { [Array]::Copy([BitConverter]::GetBytes([uint32]($v -band 0xFFFFFFFFL)), 0, $b, $o, 4) }
function Put16([byte[]]$b, [int]$o, [int]$v) { [Array]::Copy([BitConverter]::GetBytes([uint16]($v -band 0xFFFF)), 0, $b, $o, 2) }
function Word-Bytes([long]$w) { return ,([BitConverter]::GetBytes([uint32]($w -band 0xFFFFFFFFL))) }
function Hex([string]$s) { return [Convert]::ToInt64($s, 16) }
function Sha([byte[]]$b) {
    $h = [System.Security.Cryptography.SHA256]::Create()
    try { return (($h.ComputeHash($b) | ForEach-Object { $_.ToString('x2') }) -join '') } finally { $h.Dispose() }
}
function Join-Bytes([byte[]]$x, [byte[]]$y) {
    $r = New-Object byte[] ($x.Length + $y.Length)
    [Array]::Copy($x, 0, $r, 0, $x.Length); [Array]::Copy($y, 0, $r, $x.Length, $y.Length)
    return ,$r
}
function Hex-Bytes([string]$s) {
    $r = New-Object byte[] ($s.Length / 2)
    for ($i = 0; $i -lt $r.Length; $i++) { $r[$i] = [Convert]::ToByte($s.Substring(2 * $i, 2), 16) }
    return ,$r
}
function Read-At([System.IO.FileStream]$fs, [long]$offset, [int]$count) {
    $buf = New-Object byte[] $count
    [void]$fs.Seek($offset, [System.IO.SeekOrigin]::Begin)
    $got = 0
    while ($got -lt $count) {
        $n = $fs.Read($buf, $got, $count - $got)
        if ($n -le 0) { throw "Unexpected end of file at offset $offset." }
        $got += $n
    }
    return ,$buf
}
function Write-At([System.IO.FileStream]$fs, [long]$offset, [byte[]]$data) {
    [void]$fs.Seek($offset, [System.IO.SeekOrigin]::Begin)
    $fs.Write($data, 0, $data.Length)
}
function Get-Serial([System.IO.FileStream]$fs) {
    try {
        $pvd = Read-At $fs (16 * $SECTOR) $SECTOR
        $rootLba = I32 $pvd 158; $rootLen = I32 $pvd 166
        $dir = Read-At $fs ([long]$rootLba * $SECTOR) ([Math]::Min([Math]::Max($rootLen, $SECTOR), 65536))
        $p = 0
        while ($p -lt $dir.Length - 34) {
            $len = [int]$dir[$p]
            if ($len -eq 0) { $p = ([int][Math]::Floor($p / $SECTOR) + 1) * $SECTOR; continue }
            $nl = [int]$dir[$p + 32]
            if ($p + 33 + $nl -gt $dir.Length) { break }
            $name = [System.Text.Encoding]::ASCII.GetString($dir, $p + 33, $nl)
            if ($name -like 'SYSTEM.CNF*') {
                $lba = I32 $dir ($p + 2); $size = I32 $dir ($p + 10)
                $cnf = [System.Text.Encoding]::ASCII.GetString((Read-At $fs ([long]$lba * $SECTOR) ([Math]::Min([Math]::Max($size, 1), $SECTOR))))
                if ($cnf -match '(S[A-Z]{3})_(\d{3})\.(\d{2})') { return ('{0}-{1}{2}' -f $Matches[1], $Matches[2], $Matches[3]) }
                return $null
            }
            $p += $len
        }
    } catch { }
    return $null
}
function Get-Armor([System.IO.FileStream]$fs) {
    $toc = Read-At $fs ([long]$TOC_LBA * $SECTOR) $TOC_SIZE
    $ofs = 0; $found = -1
    for ($i = 0; $i -lt 24; $i++) {
        if ($ofs + 8 -gt $toc.Length) { break }
        $hs = I32 $toc $ofs
        if ($hs -lt 8 -or $hs -gt 0xFFFF -or ($ofs + $hs) -gt $toc.Length) { break }
        if ($hs -eq $HDR_UYA) { $found = $ofs; break }
        $ofs += $hs
    }
    if ($found -lt 0) { throw 'Could not find the ARMOR table. Is this Up Your Arsenal?' }
    $tbl = New-Object byte[] $HDR_UYA
    [Array]::Copy($toc, $found, $tbl, 0, $HDR_UYA)
    $wadPos = [long](I32 $tbl 4) * $SECTOR
    $copy = Read-At $fs $wadPos $HDR_UYA
    for ($j = 8; $j -lt $HDR_UYA; $j++) {
        if ($copy[$j] -ne $tbl[$j]) { throw 'The two copies of the ARMOR table disagree. Not touching this disc.' }
    }
    return [pscustomobject]@{ TocPos = [long]$TOC_LBA * $SECTOR + $found; WadPos = $wadPos; Table = $tbl }
}
function Get-Entry([byte[]]$tbl, [int]$i) {
    $f = 8 + 16 * $i
    return [pscustomobject]@{ Field = $f; MeshOfs = (I32 $tbl $f); MeshSize = (I32 $tbl ($f + 4)); TexOfs = (I32 $tbl ($f + 8)); TexSize = (I32 $tbl ($f + 12)) }
}
function Read-Entry([System.IO.FileStream]$fs, $armor, [int]$i) {
    $en = Get-Entry $armor.Table $i
    $mesh = Read-At $fs ($armor.WadPos + [long]$en.MeshOfs * $SECTOR) ($en.MeshSize * $SECTOR)
    $tex  = Read-At $fs ($armor.WadPos + [long]$en.TexOfs  * $SECTOR) ($en.TexSize  * $SECTOR)
    return [pscustomobject]@{ Mesh = $mesh; Tex = $tex }
}
# Level id -> position of its code overlay on the disc (same method as dump_overlays.ps1).
function Get-Overlays([System.IO.FileStream]$fs) {
    $toc = Read-At $fs ([long]$TOC_LBA * $SECTOR) $TOC_SIZE
    $ofs = 0
    while ($ofs + 8 -le $toc.Length) { $hs = I32 $toc $ofs; if ($hs -lt 8 -or $hs -gt 0xFFFF) { break }; $ofs += $hs }
    $map = @{}
    for ($i = 0; $i -lt 100; $i++) {
        $e = $ofs + $i * 24
        if ($e + 24 -gt $toc.Length) { break }
        for ($j = 0; $j -lt 3; $j++) {
            $lba = I32 $toc ($e + 8 * $j)
            $ho = ([long]$lba - $TOC_LBA) * $SECTOR
            if ($lba -le $TOC_LBA -or $ho + 0x60 -gt $toc.Length) { continue }
            if ((I32 $toc ([int]$ho)) -ne 0x60) { continue }
            $wad = I32 $toc ([int]$ho + 4); $id = I32 $toc ([int]$ho + 8); $dOfs = I32 $toc ([int]$ho + 0x10)
            $dataLba = [long]$wad + $dOfs
            if ($dataLba * $SECTOR + 0x60 -gt $fs.Length) { continue }
            $dh = Read-At $fs ($dataLba * $SECTOR) 0x60
            $map[$id] = [pscustomobject]@{ Pos = $dataLba * $SECTOR + (I32 $dh 0); Size = (I32 $dh 4) }
        }
    }
    return $map
}

